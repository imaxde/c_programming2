#pragma once

#include "graph.h"

#include <stdio.h>

struct Map {
    struct Graph* graph;
    int stateCount;
    // Номер государства для каждого города или -1, если город ещё ничей
    int* owner;
};

// Читает из файла число городов n и число дорог m, затем m дорог "i j len", число столиц k и k номеров столиц
// Города нумеруются с 1, государства идут в порядке столиц, столицы сразу принадлежат своим государствам
// Возвращает NULL, если файл некорректный или не хватило памяти
struct Map* readMap(FILE* file);

// Освобождает карту вместе с графом
void freeMap(struct Map* map);

// По очереди добавляет каждому государству ближайший ничейный город, соединённый дорогой с одним из его городов,
// при равных расстояниях берётся город с меньшим номером, государство без таких соседей пропускает ход
// Возвращает число городов, у которых есть государство (меньше числа городов, если граф несвязный),
// или -1, если не хватило памяти
int distributeCities(struct Map* map);

// Печатает номера государств и списки их городов по возрастанию, возвращает false, если не хватило памяти
bool printStates(FILE* file, struct Map* map);
